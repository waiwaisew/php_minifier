<?php
namespace Waiwaisew\Minifier;

/* =============================================================================
 * PART 2 – VARIABLE MANGLER
 * Renames local variables and parameters inside every function body.
 * ============================================================================= */
class JsMangler
{
    // JS keywords — never usable as variable names
    private const KW = [
        'break','case','catch','class','const','continue','debugger','default',
        'delete','do','else','enum','export','extends','false','finally','for',
        'function','if','implements','import','in','instanceof','interface','let',
        'new','null','package','private','protected','public','return','static',
        'super','switch','this','throw','true','try','typeof','undefined','var',
        'void','while','with','yield','async','await','of','from',
        'arguments','eval','target','meta','as',
    ];

    // Globals / built-ins — never rename even if they appear as local names
    private const PROTECT = [
        'window','document','console','navigator','location','history',
        'screen','performance','crypto','alert','confirm','prompt',
        'setTimeout','setInterval','clearTimeout','clearInterval',
        'requestAnimationFrame','cancelAnimationFrame','queueMicrotask',
        'fetch','XMLHttpRequest','WebSocket','EventSource','Worker',
        'Blob','File','FileReader','FormData',
        'URL','URLSearchParams','Headers','Request','Response',
        'Event','CustomEvent','EventTarget',
        'MutationObserver','IntersectionObserver','ResizeObserver',
        'localStorage','sessionStorage','indexedDB',
        'Math','JSON','Object','Function','Array','String','Number','Boolean',
        'Symbol','BigInt','Date','RegExp','Error','TypeError','RangeError',
        'SyntaxError','ReferenceError','EvalError','URIError',
        'Promise','Proxy','Reflect','Map','Set','WeakMap','WeakSet','WeakRef',
        'ArrayBuffer','DataView','Atomics','SharedArrayBuffer',
        'Int8Array','Uint8Array','Uint8ClampedArray',
        'Int16Array','Uint16Array','Int32Array','Uint32Array',
        'Float32Array','Float64Array','BigInt64Array','BigUint64Array',
        'TextEncoder','TextDecoder','ReadableStream','WritableStream',
        'parseInt','parseFloat','isNaN','isFinite',
        'encodeURIComponent','decodeURIComponent','encodeURI','decodeURI',
        'NaN','Infinity','undefined','null','true','false','globalThis','self',
        '$','jQuery',
        'module','exports','require','process','Buffer','__dirname','__filename',
    ];

    /** @var array[] tokens: ['t'=>type,'v'=>value,'r'=>null|renamed] */
    private array $tok = [];

    // -------------------------------------------------------------------------
    // Public API
    // -------------------------------------------------------------------------

    public function mangle(string $code): string
    {
        $this->tok = $this->tokenize($code);
        $this->scanForFunctions(0, count($this->tok) - 1, []);
        return $this->reconstruct();
    }

    // -------------------------------------------------------------------------
    // Tokenizer
    // -------------------------------------------------------------------------

    private function tokenize(string $code): array
    {
        $tokens = [];
        $pos = 0;
        $len = strlen($code);

        while ($pos < $len) {
            $ch = $code[$pos];

            // Skip all whitespace — spacing is regenerated by reconstruct()
            if ($ch === ' ' || $ch === "\t" || $ch === "\n" || $ch === "\r") {
                $pos++;
                continue;
            }

            // --- identifier or keyword ---
            if (preg_match('/[a-zA-Z_$]/', $ch)) {
                $s = $pos;
                while ($pos < $len && preg_match('/[\w$]/', $code[$pos])) $pos++;
                $v = substr($code, $s, $pos - $s);
                $tokens[] = ['t' => in_array($v, self::KW) ? 'kw' : 'id', 'v' => $v, 'r' => null];
                continue;
            }

            // --- number ---
            if (ctype_digit($ch) || ($ch === '.' && isset($code[$pos+1]) && ctype_digit($code[$pos+1]))) {
                $s = $pos;
                if ($ch==='0' && isset($code[$pos+1]) && in_array($code[$pos+1],['x','X','b','B','o','O'])) {
                    $pos += 2;
                    while ($pos<$len && preg_match('/[0-9a-fA-F_]/i',$code[$pos])) $pos++;
                } else {
                    while ($pos<$len && preg_match('/[0-9._]/',$code[$pos])) $pos++;
                    if ($pos<$len && in_array($code[$pos],['e','E'])) {
                        $pos++;
                        if ($pos<$len && in_array($code[$pos],['+','-'])) $pos++;
                        while ($pos<$len && ctype_digit($code[$pos])) $pos++;
                    }
                    if ($pos<$len && $code[$pos]==='n') $pos++; // BigInt
                }
                $tokens[] = ['t'=>'num','v'=>substr($code,$s,$pos-$s),'r'=>null];
                continue;
            }

            // --- quoted string ---
            if ($ch==='"'||$ch==="'") {
                $s=$pos; $q=$ch; $pos++;
                while ($pos<$len) {
                    if ($code[$pos]==='\\') { $pos+=2; continue; }
                    if ($code[$pos]===$q) { $pos++; break; }
                    $pos++;
                }
                $tokens[] = ['t'=>'str','v'=>substr($code,$s,$pos-$s),'r'=>null];
                continue;
            }

            // --- template literal (opaque token, we handle ${} during rename) ---
            if ($ch==='`') {
                $s=$pos++;
                $pos = $this->skipTpl($code,$pos,$len);
                $tokens[] = ['t'=>'tmpl','v'=>substr($code,$s,$pos-$s),'r'=>null];
                continue;
            }

            // --- comment ---
            // Must come before the regex branch: a banner such as
            // `/*! lib | https://x.com/y */` otherwise reads as a regex that
            // terminates at the first inner slash, and the rest of the comment
            // is re-tokenised as code (spacing rewritten, `//` introduced).
            if ($ch==='/' && ($code[$pos+1] ?? '') === '/') {
                $s=$pos;
                while ($pos<$len && $code[$pos] !== "\n") $pos++;
                $tokens[] = ['t'=>'cmt','v'=>substr($code,$s,$pos-$s),'r'=>null];
                continue;
            }
            if ($ch==='/' && ($code[$pos+1] ?? '') === '*') {
                $s=$pos; $pos+=2;
                while ($pos<$len) {
                    if ($code[$pos]==='*' && ($code[$pos+1] ?? '')==='/') { $pos+=2; break; }
                    $pos++;
                }
                $tokens[] = ['t'=>'cmt','v'=>substr($code,$s,$pos-$s),'r'=>null];
                continue;
            }

            // --- regex ---
            if ($ch==='/' && $this->isRegexCtx($tokens)) {
                $s=$pos++;
                $inCls=false;
                while ($pos<$len) {
                    $c=$code[$pos];
                    if ($c==='\\') { $pos+=2; continue; }
                    if ($c==='[') { $inCls=true; $pos++; continue; }
                    if ($c===']') { $inCls=false; $pos++; continue; }
                    if ($c==='/'&&!$inCls) { $pos++; break; }
                    $pos++;
                }
                while ($pos<$len && preg_match('/[gimsuy]/',$code[$pos])) $pos++;
                $tokens[] = ['t'=>'rx','v'=>substr($code,$s,$pos-$s),'r'=>null];
                continue;
            }

            // --- multi-char operators ---
            $t3=substr($code,$pos,3); $t2=substr($code,$pos,2);
            if (in_array($t3,['===','!==','**=','&&=','||=','??=','...','>>>','<<=','>>='])) {
                $tokens[]=['t'=>'op','v'=>$t3,'r'=>null]; $pos+=3;
            } elseif (in_array($t2,['=>','==','!=','<=','>=','+=','-=','*=','/=','%=',
                                    '**','&&','||','??','++','--','<<','>>','?.','->'])) {
                $tokens[]=['t'=>'op','v'=>$t2,'r'=>null]; $pos+=2;
            } else {
                $tokens[]=['t'=>'op','v'=>$ch,'r'=>null]; $pos++;
            }
        }

        return $tokens;
    }

    /** Skip to end of template literal (pos is just after opening backtick). Returns pos after closing backtick. */
    private function skipTpl(string $code, int $pos, int $len): int
    {
        while ($pos < $len) {
            $ch = $code[$pos];
            if ($ch==='\\') { $pos+=2; continue; }
            if ($ch==='`') return $pos+1;
            if ($ch==='$'&&($code[$pos+1]??'')==='{') {
                $pos+=2; $depth=1;
                while ($pos<$len&&$depth>0) {
                    $c=$code[$pos];
                    if ($c==='`') { $pos=$this->skipTpl($code,$pos+1,$len); continue; }
                    if ($c==='{') $depth++;
                    elseif ($c==='}') $depth--;
                    $pos++;
                }
                continue;
            }
            $pos++;
        }
        return $pos;
    }

    private function isRegexCtx(array $tokens): bool
    {
        for ($i=count($tokens)-1;$i>=0;$i--) {
            $t=$tokens[$i];
            if ($t['t']==='cmt') continue;   // a comment is not a value
            if ($t['t']==='kw') return in_array($t['v'],['return','typeof','instanceof','in','of','delete','void','throw','new','case','yield','await']);
            if (in_array($t['t'],['id','num'])) return false;
            if ($t['t']==='op') return !in_array($t['v'],[')',']','++','--']);
            break;
        }
        return true;
    }

    // -------------------------------------------------------------------------
    // Scope scanner — finds function bodies and triggers mangling
    // -------------------------------------------------------------------------

    /**
     * Scan tokens[s..e] for function scopes and mangle each one.
     * $outerUsed: short names already allocated in ancestor scopes.
     */
    private function scanForFunctions(int $s, int $e, array $outerMap): void
    {
        $i = $s;
        while ($i <= $e) {
            $t = $this->tok[$i];

            // Classic / generator / async function keyword
            if ($t['t']==='kw' && $t['v']==='function') {
                $i = $this->handleFunctionKw($i, $e, $outerMap);
                continue;
            }

            // Method shorthand:  m(){}  get v(){}  static m(){}  class methods
            if ($t['t']==='id' && ($mp = $this->methodParenAt($i, $e)) !== null) {
                $i = $this->handleMethod($i, $mp, $e, $outerMap);
                continue;
            }

            // Arrow function:  =>  followed by  {
            if ($t['t']==='op' && $t['v']=='=>') {
                if (isset($this->tok[$i+1]) && $this->tok[$i+1]['v']==='{') {
                    $params    = $this->arrowParams($i);
                    $bodyEnd   = $this->matchBrace($i+1, $e);
                    $renameMap = $this->mangleFunctionBody($i+2, $bodyEnd-1, $params, $outerMap);
                    // Rename param tokens in the arrow SIGNATURE (before =>)
                    $this->applyMapToArrowSig($i, $renameMap);
                    $i = $bodyEnd+1;
                    continue;
                }
                // Expression-body arrow:  (a, b) => a + b
                // It is a scope of its own. Treating it as part of the parent
                // let an outer rename (lib -> p) land inside an arrow whose own
                // parameter was already called `p`, so `(t, p) => lib.animate(t, p)`
                // became `(t, p) => p.animate(t, p)` — the param shadowed it.
                $bodyEnd = $this->arrowExprEnd($i+1, $e);
                if ($bodyEnd >= $i+1) {
                    $params    = $this->arrowParams($i);
                    $renameMap = $this->mangleFunctionBody($i+1, $bodyEnd, $params, $outerMap);
                    $this->applyMapToArrowSig($i, $renameMap);
                    $i = $bodyEnd+1;
                    continue;
                }
            }

            $i++;
        }
    }

    /**
     * If tokens[$i] starts a method shorthand — `name(params){` — return the
     * index of its `(`, otherwise null.
     *
     * Control-flow headers (`if(...)  {`, `while(...) {`, `catch(e){`, ...) can
     * never match because every one of those words tokenises as 'kw', not 'id'.
     * The token in front must be one that legitimately precedes a method:
     * `{` `}` `,` `;` `*`, or a get/set/static/async modifier.
     */
    private function methodParenAt(int $i, int $e): ?int
    {
        if (($this->tok[$i+1]['v'] ?? '') !== '(') return null;

        $prev = $i > 0 ? $this->tok[$i-1] : null;
        if ($prev === null) return null;
        $pv = $prev['v'];
        $ok = in_array($pv, ['{', '}', ',', ';', '*'], true)
           || ($prev['t'] === 'kw' && in_array($pv, ['static', 'async', 'get', 'set'], true))
           || ($prev['t'] === 'id' && in_array($pv, ['get', 'set'], true));
        if (!$ok) return null;

        $close = $this->matchParen($i+1, $e);
        if (($this->tok[$close+1]['v'] ?? '') !== '{') return null;
        return $i+1;
    }

    /** Mangle a method shorthand body and its parameter list. Returns index after it. */
    private function handleMethod(int $nameI, int $paramOpen, int $e, array $outerMap): int
    {
        $closeP = $this->matchParen($paramOpen, $e);
        $params = $this->collectParamsFromParen($paramOpen, $e);
        $bodyI  = $closeP + 1;
        $bodyEnd = $this->matchBrace($bodyI, $e);
        $map = $this->mangleFunctionBody($bodyI+1, $bodyEnd-1, $params, $outerMap);
        $this->applyMapToParenRange($paramOpen, $closeP, $map);
        return $bodyEnd + 1;
    }

    /** Handle a `function` keyword token and its following body. */
    private function handleFunctionKw(int $kwi, int $e, array $outerMap): int
    {
        $i = $kwi+1;
        if ($i<=$e && $this->tok[$i]['v']==='*') $i++;          // generator *
        if ($i<=$e && $this->tok[$i]['t']==='id') $i++;          // optional name
        if ($i>$e || $this->tok[$i]['v']!=='(') return $i;       // must have (

        $paramOpen = $i;
        $params    = $this->collectParamsFromParen($i, $e);
        $closeP    = $this->matchParen($i, $e);
        $i         = $closeP+1;

        if ($i>$e || $this->tok[$i]['v']!=='{') return $i;       // must have body {

        $bodyEnd   = $this->matchBrace($i, $e);
        $renameMap = $this->mangleFunctionBody($i+1, $bodyEnd-1, $params, $outerMap);
        // Rename param tokens in the function SIGNATURE
        $this->applyMapToParenRange($paramOpen, $closeP, $renameMap);
        return $bodyEnd+1;
    }

    /**
     * Apply renameMap to arrow function param tokens in the signature (before =>).
     * Handles:  (p1, p2) =>   p =>   async (p) =>
     */
    private function applyMapToArrowSig(int $arrowI, array $map): void
    {
        if (empty($map)) return;
        $prev = $arrowI - 1;
        if ($prev >= 0 && $this->tok[$prev]['v'] === ')') {
            // Parenthesised params: find matching (
            $depth = 0; $j = $prev;
            while ($j >= 0) {
                $v = $this->tok[$j]['v'];
                if ($v === ')') $depth++;
                elseif ($v === '(') { $depth--; if ($depth === 0) break; }
                $j--;
            }
            $this->applyMapToParenRange($j, $prev, $map);
        } elseif ($prev >= 0 && $this->tok[$prev]['t'] === 'id') {
            // Single bare param:  p =>
            $n = $this->tok[$prev]['v'];
            if (isset($map[$n])) $this->tok[$prev]['r'] = $map[$n];
        }
    }

    /**
     * Apply renameMap to identifier tokens strictly between $open and $close
     * (a parenthesis range), skipping property accesses and destructuring keys.
     */
    private function applyMapToParenRange(int $open, int $close, array $map): void
    {
        if (empty($map)) return;
        $braceDepth = 0;
        for ($i = $open + 1; $i < $close; $i++) {
            $v = $this->tok[$i]['v'];
            if ($v === '{') { $braceDepth++; continue; }
            if ($v === '}') { $braceDepth--; continue; }

            $tok = &$this->tok[$i];
            if ($tok['t'] !== 'id') continue;
            $v = $tok['v'];
            if (!isset($map[$v])) continue;
            $prev = $i > 0 ? $this->tok[$i-1]['v'] : '';
            $next = $this->tok[$i+1]['v'] ?? '';
            if (in_array($prev, ['.', '?.'])) continue; // property access

            if ($braceDepth > 0) {
                // Inside {} — could be shorthand destructuring pattern
                // Non-shorthand key:  {key: param}  — skip the key
                if ($next === ':' && in_array($prev, ['{', ','])) continue;
                // Shorthand:  {name}  or  {name = default}  → expand
                if (in_array($prev, ['{', ',']) && in_array($next, ['}', ',', '='])) {
                    $tok['r'] = $v . ':' . $map[$v];
                    continue;
                }
            }

            $tok['r'] = $map[$v];
        }
    }

    /**
     * Handles:  (p1, p2) =>   and   p =>   and   async (p) =>
     */
    private function arrowParams(int $arrowI): array
    {
        $prev = $arrowI-1;
        if ($prev >= 0 && $this->tok[$prev]['v']===')') {
            // Find matching (
            $depth=0; $j=$prev;
            while ($j>=0) {
                $v=$this->tok[$j]['v'];
                if ($v===')') $depth++;
                elseif ($v==='(') { $depth--; if ($depth===0) break; }
                $j--;
            }
            return $this->collectParamsFromParen($j, $prev);
        }
        // Single identifier param
        if ($prev>=0 && $this->tok[$prev]['t']==='id') {
            $n=$this->tok[$prev]['v'];
            if (!in_array($n,self::KW)&&!in_array($n,self::PROTECT)) return [$n];
        }
        return [];
    }

    /**
     * Collect parameter names from tokens[openParen..].
     * Handles simple, rest, destructured and defaulted params.
     *
     * Identifiers inside a default value are NOT parameters: in
     * `(sel, scope = root) =>` the name `root` belongs to the enclosing scope.
     * Collecting it made the arrow treat `root` as its own param and rename it
     * to a fresh letter that was never declared (ReferenceError at runtime).
     * A default starts at `=` and ends at the next `,` on the same depth or
     * when its enclosing (, [ or { closes. Covers `{a = x}` and `[b = y]` too.
     */
    private function collectParamsFromParen(int $open, int $limit): array
    {
        $params = [];
        $depth = 0;
        $defaultDepth = null;   // depth at which the current default value began

        for ($i = $open; $i <= $limit; $i++) {
            ['t' => $t, 'v' => $v] = $this->tok[$i];

            if ($t === 'op') {
                if (in_array($v, ['(', '[', '{'], true)) { $depth++; continue; }
                if (in_array($v, [')', ']', '}'], true)) {
                    if (--$depth === 0) break;
                    if ($defaultDepth !== null && $depth < $defaultDepth) $defaultDepth = null;
                    continue;
                }
                if ($v === '=' && $defaultDepth === null) { $defaultDepth = $depth; continue; }
                if ($v === ',' && $depth === $defaultDepth) { $defaultDepth = null; }
                continue;
            }

            if ($t !== 'id' || $defaultDepth !== null) continue;

            $prev = $i > 0 ? $this->tok[$i - 1]['v'] : '';
            $next = $this->tok[$i + 1]['v'] ?? '';
            // Skip: property access, destructuring key (id followed by :)
            if ($prev === '.' || $prev === '?.' || $next === ':') continue;
            if (in_array($v, self::KW, true) || in_array($v, self::PROTECT, true)) continue;

            $params[] = $v;
        }

        return array_values(array_unique($params));
    }

    // -------------------------------------------------------------------------
    // Core mangler — renames locals in a function body [s..e]
    // -------------------------------------------------------------------------

    /**
     * Mangle all local variables in [s..e].
     *
     * $outerMap : full original→short map from ALL ancestor scopes.
     *
     * Key improvement: restart the short-name counter at 0 for every scope and
     * only avoid short names whose original outer variable is actually referenced
     * (via closure) in this scope. This lets inner scopes freely reuse names like
     * 'a','b','c' that the outer scope used for variables not referenced here —
     * matching the aggressive reuse that Terser/UglifyJS produce.
     */
    private function mangleFunctionBody(int $s, int $e, array $params, array $outerMap): array
    {
        if ($s > $e) return [];

        // Collect everything declared in this scope (not entering nested functions)
        $declared = array_unique(array_merge($params, $this->collectDeclarations($s, $e)));

        // Filter to names that are safe to rename
        $toRename = array_filter($declared, fn($n) =>
            !in_array($n, self::KW) && !in_array($n, self::PROTECT)
        );

        // Names that stay unchanged must not be used as short-name targets
        $notRenamed = array_values(array_diff($declared, $toRename));

        // Forbid ALL short names already allocated in any ancestor scope.
        // $outerMap holds the merged original->short map for every ancestor,
        // so array_values($outerMap) is the complete set of taken letters.
        // This stops inner functions from reusing a,b,c... that parents use.
        $ancestorShortNames = array_values($outerMap);
        $outerTaken = $this->outerRefsInScope($s, $e, $outerMap, $declared);
        $forbidden  = array_unique(array_merge($ancestorShortNames, $outerTaken, $notRenamed));

        // Assign fresh short names — restart counter at 0 for every scope so
        // every function begins with a,b,c... where possible.
        $taken     = [];
        $renameMap = [];

        foreach ($toRename as $orig) {
            $ni = 0;
            do { $short = self::iToName($ni++); }
            while (in_array($short, self::KW)
                || in_array($short, self::PROTECT)
                || in_array($short, $forbidden)
                || in_array($short, $taken));
            $renameMap[$orig] = $short;
            $taken[] = $short;
        }

        if (empty($renameMap) && empty($outerMap)) {
            // Nothing to rename at all — just recurse into nested scopes
            $this->scanForFunctions($s, $e, $outerMap);
            return [];
        }

        // Full map visible inside this scope: outer context + local renames
        // Local renames override outer names (shadowing).
        $fullMap = array_merge($outerMap, $renameMap);

        // --- Apply renaming to tokens in [s..e], skipping nested function bodies ---
        $nestedBodies = $this->findNestedFunctionBodies($s, $e);
        $skip = [];
        foreach ($nestedBodies as [$ns,$ne]) {
            for ($k=$ns;$k<=$ne;$k++) $skip[$k]=true;
        }

        $braceStack = [];  // stack of 'object'|'block' for every non-skipped {
        for ($i = $s; $i <= $e; $i++) {
            if (isset($skip[$i])) continue;

            $tok = &$this->tok[$i];

            // Track brace type: distinguish code blocks { from object literals {
            if ($tok['t'] === 'op') {
                if ($tok['v'] === '{') {
                    $prevV = $i > 0 ? $this->tok[$i-1]['v'] : '';
                    $prevT = $i > 0 ? $this->tok[$i-1]['t'] : '';
                    // Code block: { after ) closes a control-flow header, or after else/try/finally/do, or after =>
                    $isBlock = $prevV === ')'
                        || $prevV === '=>'
                        || ($prevT === 'kw' && in_array($prevV, ['else','try','finally','do'], true));
                    // A class body looks like an object literal but is not one:
                    // `class A { x = 1 }` is a field, and rewriting it to the
                    // shorthand form `x:a` would change it into a syntax error.
                    if (!$isBlock && $this->isClassBodyBrace($i)) {
                        $braceStack[] = 'class';
                        continue;
                    }
                    $braceStack[] = $isBlock ? 'block' : 'object';
                    continue;
                }
                if ($tok['v'] === '}') {
                    array_pop($braceStack);
                    continue;
                }
            }

            // Apply renaming inside template literal ${...} expressions
            if ($tok['t']==='tmpl') {
                $tok['r'] = $this->renameInTemplate($tok['r']??$tok['v'], $fullMap);
                continue;
            }

            if ($tok['t']!=='id') continue;
            $orig = $tok['v'];
            if (!isset($fullMap[$orig])) continue;

            // Skip property access:  obj.name  or  obj?.name
            if ($i > 0 && in_array($this->tok[$i-1]['v'], ['.', '?.'])) continue;

            $prev = $i > 0 ? $this->tok[$i-1]['v'] : '';
            $next = $this->tok[$i+1]['v'] ?? '';

            // Shorthand expansion only inside an object literal {}, never in code blocks
            $inObj = !empty($braceStack) && end($braceStack) === 'object';
            if ($inObj) {
                // Non-shorthand object key:  { key: value }  — skip key, rename value
                if ($next === ':' && in_array($prev, ['{', ','], true)) continue;

                // Shorthand:  {name}  {name,}  {name=default}  → {name:newName}
                if (in_array($prev, ['{', ','], true) && in_array($next, ['}', ',', '='], true)) {
                    $tok['r'] = $orig . ':' . $fullMap[$orig];
                    continue;
                }
            }

            $tok['r'] = $fullMap[$orig];
        }

        // Recurse into nested function bodies passing the full merged map
        $this->scanForFunctions($s, $e, $fullMap);
        return $renameMap;
    }

    /**
     * True when the `{` at $i opens a class body: walk back over the optional
     * name and `extends Base` clause and look for the `class` keyword.
     */
    private function isClassBodyBrace(int $i): bool
    {
        for ($j = $i - 1; $j >= 0; $j--) {
            $t = $this->tok[$j];
            if ($t['t'] === 'id' || $t['v'] === '.') continue;
            if ($t['t'] === 'kw' && $t['v'] === 'extends') continue;
            return $t['t'] === 'kw' && $t['v'] === 'class';
        }
        return false;
    }

    /**
     * Scan tokens[s..e] for identifiers that reference outer-scope variables.
     * Returns the SET of short names (values in $outerMap) that are actually
     * used here — these must not be reused as new short names in this scope.
     *
     * Identifiers that are in $localDecl are local declarations (they shadow
     * the outer variable), so their outer short name is NOT marked as taken.
     */
    private function outerRefsInScope(int $s, int $e, array $outerMap, array $localDecl): array
    {
        if (empty($outerMap)) return [];

        $nestedBodies = $this->findNestedFunctionBodies($s, $e);
        $skip = [];
        foreach ($nestedBodies as [$ns,$ne])
            for ($k=$ns;$k<=$ne;$k++) $skip[$k]=true;

        $taken = [];

        for ($i = $s; $i <= $e; $i++) {
            if (isset($skip[$i])) continue;
            $tok = $this->tok[$i];

            // Scan template literal bodies for outer references
            if ($tok['t']==='tmpl') {
                foreach ($outerMap as $origName => $shortName) {
                    if (in_array($origName, $localDecl, true)) continue;
                    // Whole-word match: a plain strpos() made the name 'e' look
                    // referenced by every template containing the letter e, which
                    // needlessly burned short names.
                    if (preg_match('/(?<![\w$])' . preg_quote($origName, '/') . '(?![\w$])/', $tok['v'])) {
                        $taken[] = $shortName;
                    }
                }
                continue;
            }

            if ($tok['t'] !== 'id') continue;
            $name = $tok['v'];

            // Locally declared: shadows the outer var, outer short name stays free
            if (in_array($name, $localDecl, true)) continue;

            // Skip property accesses — not a variable reference
            if ($i > 0 && in_array($this->tok[$i-1]['v'], ['.', '?.'])) continue;

            if (isset($outerMap[$name])) {
                $taken[] = $outerMap[$name];
            }
        }

        return array_unique($taken);
    }

    // -------------------------------------------------------------------------
    // Declaration collector — gathers var/let/const/catch names at top level
    // -------------------------------------------------------------------------

    private function collectDeclarations(int $s, int $e): array
    {
        $decl = [];
        $skip = [];
        foreach ($this->findNestedFunctionBodies($s,$e) as [$ns,$ne])
            for ($k=$ns;$k<=$ne;$k++) $skip[$k]=true;

        $i = $s;
        while ($i <= $e) {
            if (isset($skip[$i])) { $i++; continue; }
            $t = $this->tok[$i];

            // var / let / const  declaration
            if ($t['t']==='kw' && in_array($t['v'],['var','let','const'])) {
                $j = $i+1;
                if ($j<=$e) {
                    $nt = $this->tok[$j];
                    if ($nt['t']==='id') {
                        // Simple declarator(s): let foo  or  let a=1, b=2, c=3
                        $decl[] = $nt['v'];
                        // Scan ahead for additional comma-separated declarators
                        $k = $j+1; $d2 = 0;
                        while ($k <= $e) {
                            $kv = $this->tok[$k]['v'];
                            if (in_array($kv, ['(','[','{'])) { $d2++; $k++; continue; }
                            if (in_array($kv, [')',']','}'])) {
                                if ($d2 === 0) break; // left the declaration context
                                $d2--; $k++; continue;
                            }
                            if ($d2 === 0 && $kv === ';') break;
                            if ($d2 === 0 && $kv === ',') {
                                $k++;
                                if ($k <= $e && $this->tok[$k]['t'] === 'id')
                                    $decl[] = $this->tok[$k]['v'];
                                continue;
                            }
                            $k++;
                        }
                    } elseif ($nt['v']==='{') {
                        // Object destructuring: let {a, b: localB, ...rest}
                        $depth=0; $k=$j;
                        while ($k<=$e) {
                            $v=$this->tok[$k]['v']; $tt=$this->tok[$k]['t'];
                            if ($v==='{') $depth++;
                            elseif ($v==='}') { $depth--; if($depth===0) break; }
                            elseif ($tt==='id'&&$depth===1) {
                                $nxt=$this->tok[$k+1]['v']??'';
                                $prv=$this->tok[$k-1]['v']??'';
                                if ($prv===':') $decl[]=$this->tok[$k]['v'];      // {key: localName}
                                elseif ($nxt!==':') $decl[]=$this->tok[$k]['v']; // {shorthand}
                            }
                            $k++;
                        }
                    } elseif ($nt['v']==='[') {
                        // Array destructuring: let [a, b, ...rest]
                        $depth=0; $k=$j;
                        while ($k<=$e) {
                            $v=$this->tok[$k]['v']; $tt=$this->tok[$k]['t'];
                            if ($v==='[') $depth++;
                            elseif ($v===']') { $depth--; if($depth===0) break; }
                            elseif ($tt==='id'&&$depth===1) $decl[]=$this->tok[$k]['v'];
                            $k++;
                        }
                    }
                }
            }

            // Local function declaration: `function helper(){}` / `function* g(){}`.
            // The body itself is skipped above, so only the name is picked up here.
            // Top-level code never reaches collectDeclarations(), so exported and
            // globally-referenced functions keep their names.
            if ($t['t']==='kw' && $t['v']==='function') {
                $j = $i+1;
                if ($j<=$e && $this->tok[$j]['v']==='*') $j++;
                if ($j<=$e && $this->tok[$j]['t']==='id'
                    && ($this->tok[$j+1]['v'] ?? '') === '(') {
                    $decl[] = $this->tok[$j]['v'];
                }
            }

            // catch (err)
            if ($t['t']==='kw'&&$t['v']==='catch') {
                if (isset($this->tok[$i+1])&&$this->tok[$i+1]['v']==='('
                 && isset($this->tok[$i+2])&&$this->tok[$i+2]['t']==='id') {
                    $decl[] = $this->tok[$i+2]['v'];
                }
            }

            $i++;
        }

        return array_unique($decl);
    }

    // -------------------------------------------------------------------------
    // Nested function body finder
    // -------------------------------------------------------------------------

    /**
     * Return array of [bodyTokenStart, bodyTokenEnd] for every direct child function
     * body within [s..e] (the { } pairs, inclusive).
     */
    private function findNestedFunctionBodies(int $s, int $e): array
    {
        $bodies = []; $i = $s;
        while ($i <= $e) {
            $t = $this->tok[$i];

            if ($t['t']==='kw' && $t['v']==='function') {
                $j=$i+1;
                if ($j<=$e&&$this->tok[$j]['v']==='*') $j++;
                if ($j<=$e&&$this->tok[$j]['t']==='id') $j++;
                if ($j<=$e&&$this->tok[$j]['v']==='(') {
                    $cp=$this->matchParen($j,$e); $j=$cp+1;
                    if ($j<=$e&&$this->tok[$j]['v']==='{') {
                        $be=$this->matchBrace($j,$e);
                        $bodies[]=[$j,$be]; $i=$be+1; continue;
                    }
                }
            }

            if ($t['t']==='op'&&$t['v']=='=>'&&isset($this->tok[$i+1])&&$this->tok[$i+1]['v']==='{') {
                $be=$this->matchBrace($i+1,$e);
                $bodies[]=[$i+1,$be]; $i=$be+1; continue;
            }

            // Expression-body arrow: its body is a nested scope too.
            if ($t['t']==='op'&&$t['v']==='=>') {
                $be=$this->arrowExprEnd($i+1,$e);
                if ($be >= $i+1) { $bodies[]=[$i+1,$be]; $i=$be+1; continue; }
            }

            // Method shorthand bodies are scopes of their own, so their locals
            // must not be collected as declarations of the enclosing scope.
            if ($t['t']==='id' && ($mp = $this->methodParenAt($i, $e)) !== null) {
                $bodyI = $this->matchParen($mp, $e) + 1;
                $be    = $this->matchBrace($bodyI, $e);
                $bodies[]=[$bodyI,$be]; $i=$be+1; continue;
            }

            $i++;
        }
        return $bodies;
    }

    // -------------------------------------------------------------------------
    // Template literal identifier renaming
    // -------------------------------------------------------------------------

    /**
     * Apply $renameMap inside every ${...} expression of a template literal.
     * Leaves the literal (HTML/text) parts untouched.
     *
     * IMPORTANT: the replacement is done in a SINGLE left-to-right pass over the
     * expression. Looping preg_replace() over the map (the previous approach)
     * chained substitutions: with a map like ['mn'=>'e', 'e'=>'s'] the text `mn`
     * was rewritten to `e` by the first entry and then to `s` by the second, so
     * `${mn}` silently became `${s}` — a different variable.
     */
    private function renameInTemplate(string $tpl, array $renameMap): string
    {
        if (empty($renameMap)) return $tpl;

        $out = ''; $pos = 0; $len = strlen($tpl);

        while ($pos < $len) {
            $ch = $tpl[$pos];

            // Escape sequence in the literal part (covers \` and \${) — copy verbatim
            if ($ch === '\\') { $out .= substr($tpl, $pos, 2); $pos += 2; continue; }

            if ($ch === '$' && ($tpl[$pos + 1] ?? '') === '{') {
                $end = $this->matchTplExprEnd($tpl, $pos + 2, $len);
                if ($end < 0) { $out .= substr($tpl, $pos); break; }   // unterminated: leave as-is
                $expr = substr($tpl, $pos + 2, $end - $pos - 2);
                $out .= '${' . $this->renameInExpr($expr, $renameMap) . '}';
                $pos  = $end + 1;
                continue;
            }

            $out .= $ch; $pos++;
        }

        return $out;
    }

    /**
     * Index of the `}` that closes a ${ ... } expression starting at $pos,
     * or -1 if unterminated. Strings and nested template literals are skipped so
     * a brace inside them cannot end the expression.
     */
    private function matchTplExprEnd(string $s, int $pos, int $len): int
    {
        $depth = 0;
        while ($pos < $len) {
            $c = $s[$pos];
            if ($c === '\\') { $pos += 2; continue; }
            if ($c === "'" || $c === '"') { $pos = $this->skipQuoted($s, $pos, $len); continue; }
            if ($c === '`')  { $pos = $this->skipTpl($s, $pos + 1, $len); continue; }
            if ($c === '{')  { $depth++; $pos++; continue; }
            if ($c === '}')  { if ($depth === 0) return $pos; $depth--; $pos++; continue; }
            $pos++;
        }
        return -1;
    }

    /** Position just past the closing quote of the string starting at $pos. */
    private function skipQuoted(string $s, int $pos, int $len): int
    {
        $q = $s[$pos]; $pos++;
        while ($pos < $len) {
            if ($s[$pos] === '\\') { $pos += 2; continue; }
            if ($s[$pos] === $q)   { return $pos + 1; }
            $pos++;
        }
        return $len;
    }

    /**
     * Rename identifiers inside one ${ ... } expression, single pass.
     * Skips: string contents, numeric literals (so the `e` in 1e5 is never an
     * identifier), property names after `.` / `?.`, and object-literal keys.
     * Nested template literals are recursed into so their own ${} are handled.
     */
    private function renameInExpr(string $expr, array $map): string
    {
        $out = ''; $i = 0; $n = strlen($expr); $prev = '';

        while ($i < $n) {
            $c = $expr[$i];

            // --- string literal: copied verbatim ---
            if ($c === "'" || $c === '"') {
                $j = $this->skipQuoted($expr, $i, $n);
                $out .= substr($expr, $i, $j - $i);
                $i = $j; $prev = '"';
                continue;
            }

            // --- nested template literal ---
            if ($c === '`') {
                $j = $this->skipTpl($expr, $i + 1, $n);
                $out .= $this->renameInTemplate(substr($expr, $i, $j - $i), $map);
                $i = $j; $prev = '`';
                continue;
            }

            // --- numeric literal ---
            if (ctype_digit($c) || ($c === '.' && ctype_digit($expr[$i + 1] ?? ''))) {
                $s = $i;
                $i++;
                while ($i < $n && preg_match('/[0-9a-fA-FxXoObBnN._]/', $expr[$i])) {
                    // exponent sign belongs to the number: 1e-5
                    if (in_array($expr[$i], ['e', 'E'], true)
                        && in_array($expr[$i + 1] ?? '', ['+', '-'], true)) { $i += 2; continue; }
                    $i++;
                }
                $out .= substr($expr, $s, $i - $s);
                $prev = '0';
                continue;
            }

            // --- identifier ---
            if (preg_match('/[A-Za-z_$]/', $c)) {
                $s = $i;
                while ($i < $n && preg_match('/[\w$]/', $expr[$i])) $i++;
                $word = substr($expr, $s, $i - $s);

                $k = $i; while ($k < $n && ctype_space($expr[$k])) $k++;
                $next = $expr[$k] ?? '';

                if (!isset($map[$word]) || $prev === '.') {
                    $out .= $word;                       // unknown name, or obj.prop / obj?.prop
                } elseif ($next === ':' && ($prev === '{' || $prev === ',')) {
                    $out .= $word;                       // object-literal key: { key: value }
                } elseif (($prev === '{' || $prev === ',')
                          && in_array($next, ['}', ',', '='], true)) {
                    $out .= $word . ':' . $map[$word];   // shorthand { name } -> { name: a }
                } else {
                    $out .= $map[$word];
                }

                $prev = 'w';
                continue;
            }

            // --- spread / rest: `...name` is a value reference, NOT a property
            // access. Consuming it as three separate '.' characters used to leave
            // $prev === '.', so the identifier after it was skipped and kept its
            // original (now undeclared) name.
            if ($c === '.' && substr($expr, $i, 3) === '...') {
                $out .= '...'; $i += 3; $prev = '...';
                continue;
            }

            // --- optional chaining: `?.` behaves like `.` for the next word ---
            if ($c === '?' && ($expr[$i + 1] ?? '') === '.'
                && !ctype_digit($expr[$i + 2] ?? '')) {
                $out .= '?.'; $i += 2; $prev = '.';
                continue;
            }

            $out .= $c;
            if (!ctype_space($c)) $prev = $c;
            $i++;
        }

        return $out;
    }

    // -------------------------------------------------------------------------
    // Helpers
    // -------------------------------------------------------------------------

    private function matchBrace(int $open, int $limit): int
    {
        $d=0;
        for ($i=$open;$i<=$limit;$i++) {
            $v=$this->tok[$i]['v'];
            if ($v==='{') $d++; elseif ($v==='}') { $d--; if($d===0) return $i; }
        }
        return $limit;
    }

    /**
     * Last token index of an arrow's expression body starting at $s.
     * The body is an AssignmentExpression, so it ends at the first `,` `;`
     * or unmatched closer at depth 0, or at a `:` that does not belong to a
     * ternary opened inside the body. Returns $s-1 for an empty body.
     */
    private function arrowExprEnd(int $s, int $e): int
    {
        $depth = 0; $ternary = 0;
        for ($k = $s; $k <= $e; $k++) {
            $t = $this->tok[$k]; $v = $t['v'];
            if ($t['t'] === 'cmt') return $k - 1;
            if ($t['t'] !== 'op') continue;
            if ($v === '(' || $v === '[' || $v === '{') { $depth++; continue; }
            if ($v === ')' || $v === ']' || $v === '}') {
                if ($depth === 0) return $k - 1;
                $depth--; continue;
            }
            if ($depth > 0) continue;
            if ($v === ',' || $v === ';') return $k - 1;
            if ($v === '?') { $ternary++; continue; }
            if ($v === ':') {
                if ($ternary === 0) return $k - 1;
                $ternary--;
            }
        }
        return $e;
    }

    private function matchParen(int $open, int $limit): int
    {
        $d=0;
        for ($i=$open;$i<=$limit;$i++) {
            $v=$this->tok[$i]['v'];
            if ($v==='(') $d++; elseif ($v===')') { $d--; if($d===0) return $i; }
        }
        return $limit;
    }

    /** 0→a, 1→b, …, 25→z, 26→aa, 27→ab, … */
    private static function iToName(int $i): string
    {
        $c='abcdefghijklmnopqrstuvwxyz';
        if ($i<26) return $c[$i];
        return self::iToName(intdiv($i,26)-1).$c[$i%26];
    }

    private function reconstruct(): string
    {
        $out = '';
        foreach ($this->tok as $t) {
            $v = $t['r'] !== null ? $t['r'] : $t['v'];
            if ($v === '') continue;

            // Comments are emitted verbatim on their own line. A line comment
            // would otherwise swallow the code that follows it, and a block
            // comment glued to the next token is hard to read.
            if ($t['t'] === 'cmt') {
                if ($out !== '' && !str_ends_with($out, "\n")) $out .= "\n";
                $out .= $v . "\n";
                continue;
            }

            // Trailing comma before a closer is dead weight: `{a:1,}` -> `{a:1}`.
            // Array holes must survive, so bail out when the previous character
            // is itself a comma or the opening bracket.
            if (($v === '}' || $v === ']' || $v === ')') && substr($out, -1) === ',') {
                $before = substr($out, -2, 1);
                if ($before !== ',' && $before !== '[') $out = substr($out, 0, -1);
            }

            // Separate tokens that would otherwise fuse (`a` `in` -> `ain`,
            // `+` `+` -> `++`, `/` `/` -> a comment, ...).
            if ($out !== '' && self::needsSeparator($out, $v[0])) $out .= ' ';

            $out .= $v;
        }
        return $out;
    }

    /** Mirrors JsMinifier::needsSeparator for the token-based rebuild. */
    private static function needsSeparator(string $out, string $next): bool
    {
        $last    = substr($out, -1);
        $lastTwo = substr($out, -2);

        if (preg_match('/[\w$]/', $last) && preg_match('/[\w$]/', $next)) return true;
        if ($last === '+' && $next === '+') return true;
        if ($last === '-' && $next === '-') return true;
        if ($last === '/' && ($next === '/' || $next === '*')) return true;
        if ($last === '<' && $next === '!') return true;
        if ($lastTwo === '--' && $next === '>') return true;
        if ($next === '.' && ctype_digit($last)
            && !preg_match('/[A-Za-z_$][\w$]*$/', $out)
            && !preg_match('/\.[\d_]*$/', $out)) return true;

        return false;
    }
}
